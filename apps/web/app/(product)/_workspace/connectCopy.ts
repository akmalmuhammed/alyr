// Arabic counts agree with what they count: one and two have their own words, three to ten the
// plural, eleven and more the singular. (The API does the same for its own sentences: `counted()`.)
const arN = (n: number, one: string, two: string, few: string, many: string) =>
  n === 1 ? one : n === 2 ? two : `${n} ${n >= 3 && n <= 10 ? few : many}`;

const pairs = <T extends Record<string, readonly [string, string]>>(table: T, i: 0 | 1) =>
  Object.fromEntries(Object.entries(table).map(([k, v]) => [k, v[i]])) as Record<keyof T, string>;

