// Every word the Discounts screen and the discount lines on an order say, in English and
// Arabic, in one place (ALY-150, specs/014-pricing-pack; the Arabic is a draft until a native
// speaker has been through it, ALY-66). The components hold no text. Both languages are written
// against one shape, so a missing Arabic line is a type error, not a hole on a phone.
//
// Owners read "discounts", "coupon code" and "automatic discount"; never a code word of ours.
// The rule in words ("10% off orders over QAR 200") comes from the API in both languages.
// Amounts are written by `../_customer/price.ts` («QAR 24», «24 ر.ق»); where an amount sits
// inside a sentence it is wrapped in an isolate so the digits keep their order in Arabic.

import type { Lang } from "./catalogCopy";

/** Keeps an amount, a code or a date in one run inside a sentence of the other direction. */
const iso = (text: string) => `⁨${text}⁩`;

/** «مرة واحدة», «مرتين», «3 مرات», «11 مرة». */
function times(n: number): string {
  if (n === 1) return "مرة واحدة";
  if (n === 2) return "مرتين";
  return n >= 3 && n <= 10 ? `${n} مرات` : `${n} مرة`;
}

