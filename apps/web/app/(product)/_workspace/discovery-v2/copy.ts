// no text: every sentence, label, tooltip and aria-label is here. Whole sentences per language,
// never fragments joined across languages; counts go through `counted()` so Arabic agrees.
// Dates and times come in already formatted (`_ui/format.ts`, Western digits); an Arabic sentence
// wraps a time, a range or a Latin name in `isolate()` so it keeps its order.
//
// ALYR's own voice is rule-based: no first person, no AI word ("answer tools", "by rule",
// "evidence"). "Google" is said only when the source is Google; the sample and the recorded
// listing are "your listing". The Arabic is a careful draft for the native reviewer (ALY-66).

