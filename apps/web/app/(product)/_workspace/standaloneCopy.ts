// Every word the standalone parts of the Documents screens say (ALY-141, spec 016), in English
// and Arabic, in one place so a reviewer can read them together (ALY-66: the Arabic is a draft
// until a native speaker has been through it). The one-line box, the shop's customers, the saved
// lines, the payment link and the "send from your own WhatsApp" button. The components hold no
// text. Both languages are written against the same shape, so a missing Arabic line is a type
// error, not a hole on a phone. The rest of the section's words are `documentsCopy.ts`.
//
// Money is written by `documentsLogic.written` («QAR 500.00», «500.00 ر.ق»); a count and its
// noun are written whole, in each language, never joined from fragments.

import type { Lang } from "./documentsLogic";

