/** An Arabic count with its noun: one, two, three to ten (plural), eleven and more (singular). */
function countOf(n: number, one: string, two: string, few: string, many: string) {
  return n === 1 ? one : n === 2 ? two : n <= 10 ? `${n} ${few}` : `${n} ${many}`;
}

