// Every word the Documents screens say, in English and Arabic, in one place so a reviewer can
// read them together (ALY-66: the Arabic is a draft until a native speaker has been through
// it). The components hold no text. Both languages are written against the same shape, so a
// missing Arabic line is a type error, not a hole on a phone.
//
// The names of the kinds, the payment methods and the units are the ones the paper uses
// (`apps/api/src/alyr/modules/documents/words.py`), so the screen and the page say the same
// thing: «فاتورة», «إيصال», «إشعار دائن». The API's own refusals arrive already written in both
// languages (they say what to do next); nothing here repeats them.
//
// Amounts come from `documentsLogic.written` («QAR 127.00», «127.00 ر.ق»).

